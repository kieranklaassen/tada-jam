// Takes from a checkout of live-mix the part the jam's music uses, and writes it to vendor/live-mix.
//
//   git clone https://github.com/kieranklaassen/live-mix && cd live-mix && pnpm install
//   node scripts/vendor-live-mix.mjs <that checkout>
//
// The package's own entry points bring every device with them (about 1.5 MB of script for the renderer). Here the
// stock registry is replaced by one that knows only the devices in DEVICES, and nothing else of live-mix is changed.

import { execFileSync } from 'node:child_process'
import { cpSync, mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { join, resolve } from 'node:path'

const from = resolve(process.argv[2] ?? '')
const out = resolve(import.meta.dirname, '../vendor/live-mix')
const { build } = createRequire(join(from, 'package.json'))('esbuild')
const commit = execFileSync('git', ['-C', from, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim()

/** The devices a game may play its music on, by live-mix id. */
const DEVICES = ['felt-piano', 'harp', 'mallets', 'acoustic-guitar', 'clarinet', 'flute', 'string-bass', 'plate-reverb']
const WRITTEN_BY_HAND = { 'felt-piano': 'instrument', 'plate-reverb': 'reverb' }

const upper = (id) => id.replaceAll('-', '_').toUpperCase()
const registry = [
  `import { wasmDeviceDescriptor } from './descriptor'`,
  ...DEVICES.map((id) => id in WRITTEN_BY_HAND
    ? `import { ${upper(id)}_DEVICE } from './devices/${id}'`
    : `import { ${upper(id)}_DESCRIPTOR } from './devices/${id}.gen'`),
  `const all = [${DEVICES.map((id) => id in WRITTEN_BY_HAND
    ? `wasmDeviceDescriptor(${upper(id)}_DEVICE, { name: '${id}', category: '${WRITTEN_BY_HAND[id]}' })`
    : `${upper(id)}_DESCRIPTOR`).join(', ')}]`,
  `export const describeStockWasmDevice = (id) => all.find((d) => d.id === id)`,
].join('\n')

for (const dir of ['core', 'dsp', 'wasm', 'worklets']) rmSync(join(out, dir), { recursive: true, force: true })
mkdirSync(join(out, 'wasm'), { recursive: true })
mkdirSync(join(out, 'worklets'), { recursive: true })

const banner = { js: `// GENERATED by scripts/vendor-live-mix.mjs from kieranklaassen/live-mix ${commit} (MIT, see LICENSE). Do not edit.` }
const shared = { absWorkingDir: from, bundle: true, format: 'esm', target: 'es2022', banner, legalComments: 'inline', logLevel: 'error' }
await build({ ...shared, stdin: { contents: `export { createEngine } from './core/Engine'`, resolveDir: join(from, 'src'), loader: 'ts' }, outfile: join(out, 'core/index.js') })
await build({
  ...shared,
  stdin: { contents: `export { renderPatch } from './dsp/patch-render'`, resolveDir: join(from, 'src'), loader: 'ts' },
  outfile: join(out, 'dsp/render.js'),
  plugins: [{
    name: 'few-devices',
    setup(b) {
      b.onLoad({ filter: /src\/dsp\/registry\.ts$/ }, () => ({ contents: registry, loader: 'ts', resolveDir: join(from, 'src/dsp') }))
    },
  }],
})
for (const id of DEVICES) cpSync(join(from, `dist/wasm/${id}.wasm`), join(out, `wasm/${id}.wasm`))
cpSync(join(from, 'dist/worklets/wasm-device.js'), join(out, 'worklets/wasm-device.js'))
// Named by the scripts and loaded only when a meter or a load figure is asked for; a bundler wants them to be there.
for (const dir of ['core', 'dsp']) for (const name of ['meter', 'load-sampler']) cpSync(join(from, `dist/worklets/${name}.js`), join(out, `${dir}/worklets/${name}.js`))
cpSync(join(from, 'LICENSE'), join(out, 'LICENSE'))
writeFileSync(join(out, 'COMMIT'), `${commit}\n`)
